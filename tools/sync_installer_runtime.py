"""Regenerate the browser runtime from the canonical Python runtime.

Usage: python tools/sync_installer_runtime.py [--check]
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from TreeForge.core.installer_runtime import RUNTIME

output = ROOT / 'src/utils/installerRuntime.ts'
expected = '// Generated by tools/sync_installer_runtime.py; do not edit by hand.\nexport const INSTALLER_RUNTIME = String.raw`' + RUNTIME + '`;\n'
if '--check' in sys.argv:
    if not output.exists() or output.read_text(encoding='utf-8') != expected:
        raise SystemExit('Installer runtimes differ; run python tools/sync_installer_runtime.py')
else:
    output.write_text(expected, encoding='utf-8')
