/**
 * Smart Code Generator and Standalone Self-Extracting Installer Generator
 * for TreeForge.
 */

export interface CodeGeneratorOptions {
  projectName?: string;
  author?: string;
  license?: 'MIT' | 'Apache-2.0' | 'GPL-3.0' | 'Proprietary' | 'None';
  stack?: 'pyqt6' | 'fastapi' | 'data_pipeline' | 'cli_tool' | 'generic';
}

/**
 * Generate intelligent, production-ready starter code for an arbitrary file path
 * based on its extension, folder context, and filename.
 */
export function generateBoilerplateForFile(
  filePath: string,
  projectName: string = 'TreeForgeProject',
  options: CodeGeneratorOptions = {}
): string {
  const cleanPath = filePath.replace(/\\/g, '/');
  const filename = cleanPath.split('/').pop() || '';
  const ext = filename.includes('.') ? '.' + filename.split('.').pop()?.toLowerCase() : '';
  const lowerName = filename.toLowerCase();

  // Python files
  if (ext === '.py') {
    if (lowerName === '__init__.py') {
      return `"""${projectName} - Package initialization."""\n\n__version__ = "1.0.0"\n__author__ = "${options.author || 'TreeForge Developer'}"\n`;
    }

    if (lowerName === 'main.py' || lowerName === 'app.py') {
      if (options.stack === 'fastapi') {
        return `"""FastAPI application entry point for ${projectName}."""\n\nfrom fastapi import FastAPI, HTTPException\nfrom pydantic import BaseModel\n\napp = FastAPI(\n    title="${projectName} API",\n    version="1.0.0",\n    description="High-performance backend API service generated by TreeForge.",\n)\n\n\nclass HealthResponse(BaseModel):\n    status: str\n    version: str\n\n\n@app.get("/health", response_model=HealthResponse)\ndef health_check():\n    """Health check endpoint."""\n    return HealthResponse(status="healthy", version="1.0.0")\n\n\n@app.get("/")\ndef read_root():\n    return {"message": "Welcome to ${projectName} API!"}\n\n\nif __name__ == "__main__":\n    import uvicorn\n    uvicorn.run("main:app", host="0.0.0.0", port=8000, reload=True)\n`;
      }

      // Default: PyQt6 desktop or CLI
      return `"""Main application entry point for ${projectName}."""\n\nimport sys\nimport os\nfrom PyQt6.QtWidgets import QApplication\nfrom PyQt6.QtCore import Qt\n\ntry:\n    from ui.main_window import MainWindow\nexcept ImportError:\n    from PyQt6.QtWidgets import QMainWindow, QLabel, QVBoxLayout, QWidget\n    class MainWindow(QMainWindow):\n        def __init__(self):\n            super().__init__()\n            self.setWindowTitle("${projectName}")\n            self.resize(800, 600)\n            w = QWidget()\n            l = QVBoxLayout(w)\n            l.addWidget(QLabel("Welcome to ${projectName}!"))\n            self.setCentralWidget(w)\n\n\ndef main() -> None:\n    """Initialize and run the PyQt6 desktop application."""\n    app = QApplication(sys.argv)\n    app.setApplicationName("${projectName}")\n    app.setOrganizationName("TreeForge")\n\n    window = MainWindow()\n    window.show()\n\n    sys.exit(app.exec())\n\n\nif __name__ == "__main__":\n    main()\n`;
    }

    if (lowerName.includes('window') || cleanPath.includes('/ui/')) {
      const className = filename.replace('.py', '').split('_').map(s => s.charAt(0).toUpperCase() + s.slice(1)).join('');
      return `"""User Interface component: ${filename}."""\n\nfrom PyQt6.QtWidgets import (\n    QWidget, QMainWindow, QVBoxLayout, QHBoxLayout,\n    QPushButton, QLabel, QLineEdit, QStatusBar, QFrame\n)\nfrom PyQt6.QtCore import Qt, pyqtSignal\n\n\nclass ${className}(QWidget):\n    """UI Widget for ${projectName}."""\n\n    action_triggered = pyqtSignal(str)\n\n    def __init__(self, parent=None):\n        super().__init__(parent)\n        self._init_ui()\n\n    def _init_ui(self) -> None:\n        layout = QVBoxLayout(self)\n        layout.setContentsMargins(16, 16, 16, 16)\n        layout.setSpacing(12)\n\n        title = QLabel("${className}")\n        title.setStyleSheet("font-size: 16px; font-weight: bold; color: #10b981;")\n        layout.addWidget(title)\n\n        desc = QLabel("Modular component crafted with TreeForge architecture.")\n        desc.setStyleSheet("color: #94a3b8;")\n        layout.addWidget(desc)\n\n        layout.addStretch()\n`;
    }

    if (lowerName.startsWith('test_') || cleanPath.includes('/tests/')) {
      const targetModule = filename.replace('test_', '').replace('.py', '');
      return `"""Unit test suite for ${targetModule}."""\n\nimport unittest\n\n\nclass Test${targetModule.charAt(0).toUpperCase() + targetModule.slice(1)}(unittest.TestCase):\n    """Test cases for module operations."""\n\n    def setUp(self) -> None:\n        """Set up test fixtures."""\n        self.test_data = {"status": "ok", "count": 10}\n\n    def test_initialization(self) -> None:\n        """Verify standard setup and assertions."""\n        self.assertEqual(self.test_data["status"], "ok")\n        self.assertGreater(self.test_data["count"], 0)\n\n    def test_edge_case(self) -> None:\n        """Test boundary conditions."""\n        self.assertTrue(True)\n\n\nif __name__ == "__main__":\n    unittest.main()\n`;
    }

    if (lowerName.includes('worker') || lowerName.includes('thread')) {
      return `"""Background multithreaded worker using QThread."""\n\nimport time\nfrom PyQt6.QtCore import QThread, pyqtSignal\n\n\nclass WorkerThread(QThread):\n    """Background task executor with progress reporting."""\n\n    progress = pyqtSignal(int)  # 0 to 100\n    finished = pyqtSignal(object)  # result object\n    failed = pyqtSignal(str)  # error message\n\n    def __init__(self, task_params: dict, parent=None):\n        super().__init__(parent)\n        self.params = task_params\n        self._is_cancelled = False\n\n    def cancel(self) -> None:\n        """Signal thread to cancel safely."""\n        self._is_cancelled = True\n\n    def run(self) -> None:\n        """Execute background workload."""\n        try:\n            for i in range(1, 101):\n                if self._is_cancelled:\n                    return\n                time.sleep(0.02)\n                self.progress.emit(i)\n            self.finished.emit({"success": True, "total": 100})\n        except Exception as e:\n            self.failed.emit(str(e))\n`;
    }

    if (lowerName.includes('style') || lowerName.includes('theme')) {
      return `"""UI Styling and Theme Tokens for ${projectName}."""\n\nDARK_THEME = {\n    "bg_window": "#0f172a",\n    "bg_card": "#1e293b",\n    "border": "#334155",\n    "accent": "#10b981",\n    "accent_hover": "#059669",\n    "text_primary": "#f8fafc",\n    "text_secondary": "#94a3b8",\n    "error": "#ef4444",\n}\n\nLIGHT_THEME = {\n    "bg_window": "#f8fafc",\n    "bg_card": "#ffffff",\n    "border": "#e2e8f0",\n    "accent": "#059669",\n    "accent_hover": "#047857",\n    "text_primary": "#0f172a",\n    "text_secondary": "#475569",\n    "error": "#dc2626",\n}\n`;
    }

    if (lowerName.includes('settings') || lowerName.includes('config')) {
      return `"""Configuration and Persistent Settings Service."""\n\nimport json\nfrom pathlib import Path\nfrom typing import Any, Dict\n\n\nclass SettingsService:\n    """Manages application persistent state in JSON format."""\n\n    def __init__(self, config_path: str = "config.json"):\n        self.config_path = Path(config_path)\n        self._data: Dict[str, Any] = self.load()\n\n    def load(self) -> Dict[str, Any]:\n        """Load settings from disk or return default."""\n        if self.config_path.exists():\n            try:\n                with open(self.config_path, "r", encoding="utf-8") as f:\n                    return json.load(f)\n            except Exception:\n                pass\n        return {"theme": "dark", "language": "en", "auto_save": True}\n\n    def save(self) -> bool:\n        """Persist settings to disk."""\n        try:\n            with open(self.config_path, "w", encoding="utf-8") as f:\n                json.dump(self._data, f, indent=2, ensure_ascii=False)\n            return True\n        except Exception:\n            return False\n\n    def get(self, key: str, default: Any = None) -> Any:\n        return self._data.get(key, default)\n\n    def set(self, key: str, value: Any) -> None:\n        self._data[key] = value\n        self.save()\n`;
    }

    if (lowerName === 'make_zip.py') {
      return `"""Package distribution script for ${projectName}."""\n\nimport os\nimport zipfile\nfrom pathlib import Path\n\nEXCLUDE_DIRS = {"__pycache__", ".git", ".pytest_cache", ".venv", "env", "dist", "build"}\nEXCLUDE_EXTS = {".pyc", ".pyo", ".bak", ".tmp", ".zip"}\n\ndef package_project(output_zip: str = "${projectName}_Package.zip") -> None:\n    base_dir = Path(__file__).resolve().parent\n    out_file = base_dir / output_zip\n    print(f"Creating archive: {out_file}")\n    \n    with zipfile.ZipFile(out_file, "w", zipfile.ZIP_DEFLATED) as zf:\n        for root, dirs, files in os.walk(base_dir):\n            dirs[:] = [d for d in dirs if d not in EXCLUDE_DIRS and not d.startswith(".")]\n            for file in files:\n                fp = Path(root) / file\n                if fp.suffix in EXCLUDE_EXTS or file == output_zip:\n                    continue\n                rel = fp.relative_to(base_dir)\n                zf.write(fp, arcname=str(Path("${projectName}") / rel))\n    print(f"Successfully packaged -> {output_zip}")\n\nif __name__ == "__main__":\n    package_project()\n`;
    }

    // Generic Python class / module
    const moduleName = filename.replace('.py', '').split('_').map(s => s.charAt(0).toUpperCase() + s.slice(1)).join('');
    return `"""Module documentation for ${filename}."""\n\nfrom typing import Optional, List, Dict, Any\nimport logging\n\nlogger = logging.getLogger(__name__)\n\n\nclass ${moduleName}:\n    """Core operational unit for ${moduleName}."""\n\n    def __init__(self, name: str = "${moduleName}"):\n        self.name = name\n        self.is_active = True\n\n    def execute(self, *args, **kwargs) -> Dict[str, Any]:\n        """Execute core logic and return standardized result dict."""\n        logger.info(f"Executing {self.name}")\n        return {"status": "success", "module": self.name}\n\n\ndef run() -> None:\n    """Quick run helper."""\n    instance = ${moduleName}()\n    print(instance.execute())\n\n\nif __name__ == "__main__":\n    run()\n`;
  }

  // Markdown files
  if (ext === '.md') {
    return `# ${projectName}\n\n> Comprehensive project architecture scaffolded with TreeForge.\n\n## 🚀 Quick Start\n\n### Prerequisites\n- Python 3.10 or higher\n- pip package manager\n\n### Installation\n\`\`\`bash\n# 1. Create and activate virtual environment\npython -m venv .venv\nsource .venv/bin/activate  # On Windows: .venv\\Scripts\\activate\n\n# 2. Install dependencies\npip install -r requirements.txt\n\n# 3. Launch application\npython main.py\n\`\`\`\n\n## 🧪 Running Unit Tests\n\`\`\`bash\npython -m unittest discover -s tests\n\`\`\`\n\n## 📁 Architecture Overview\n- \`core/\`: Core domain logic and mathematical/algorithmic models.\n- \`ui/\`: Modern presentation layer and interface components.\n- \`services/\`: Data persistence, theme service, and API adapters.\n- \`tests/\`: Comprehensive test suites.\n\n## 📄 License\nThis project is licensed under the ${options.license || 'MIT'} License.\n`;
  }

  // Requirements file
  if (lowerName === 'requirements.txt') {
    if (options.stack === 'fastapi') {
      return `fastapi>=0.110.0\nuvicorn[standard]>=0.28.0\npydantic>=2.6.0\npytest>=8.0.0\nhttpx>=0.27.0\n`;
    }
    return `PyQt6>=6.6.0\nPyQt6-Qt6>=6.6.0\npyinstaller>=6.5.0\npytest>=8.0.0\n`;
  }

  // Gitignore
  if (lowerName === '.gitignore') {
    return `# Byte-compiled / optimized files\n__pycache__/\n*.py[cod]\n*$py.class\n*.so\n\n# Virtual environments\n.venv/\nenv/\nvirtualenv/\n\n# Packaging and builds\nbuild/\ndist/\n*.egg-info/\n*.zip\n\n# IDEs and Editors\n.vscode/\n.idea/\n*.swp\n*.swo\n\n# TreeForge backups\n*.bak\n*.tmp\n.env\n`;
  }

  // JSON files
  if (ext === '.json') {
    return `{\n  "name": "${projectName.toLowerCase()}",\n  "version": "1.0.0",\n  "description": "Scaffolded with TreeForge",\n  "settings": {\n    "theme": "dark",\n    "debug": false\n  }\n}\n`;
  }

  // Shell script
  if (ext === '.sh') {
    return `#!/usr/bin/env bash\n# Setup and launch script for ${projectName}\nset -e\n\necho "🚀 Starting ${projectName}..."\nif [ ! -d ".venv" ]; then\n    echo "Creating virtual environment..."\n    python3 -m venv .venv\nfi\n\nsource .venv/bin/activate\npip install --upgrade pip\npip install -r requirements.txt\npython3 main.py\n`;
  }

  // Fallback for other files
  return `# Content for ${filename}\n# Generated by TreeForge for ${projectName}\n`;
}

/**
 * Auto-generate full batch text for an entire array of file paths.
 */
export function generateFullBatchCode(
  filePaths: string[],
  projectName: string = 'TreeForgeProject',
  options: CodeGeneratorOptions = {}
): string {
  const chunks: string[] = [];

  for (const path of filePaths) {
    const code = generateBoilerplateForFile(path, projectName, options);
    chunks.push(`### ${path}\n${code.trim()}`);
  }

  return chunks.join('\n\n') + '\n';
}

/**
 * Generate a standalone, self-extracting single Python script (e.g. `create_project.py`).
 * Running `python create_project.py` anywhere on any OS recreates all directories,
 * writes all file contents, creates virtualenv, and prints a success banner!
 */
export function generateStandalonePythonInstaller(
  files: Record<string, string>,
  projectName: string = 'TreeForgeProject'
): string {
  const filesJson = JSON.stringify(files, null, 2);

  return `#!/usr/bin/env python3
"""Standalone Self-Extracting Installer for ${projectName}.
Generated automatically by TreeForge.

Run this script directly:
    python create_project.py
"""

import os
import sys
import json
import base64
from pathlib import Path

PROJECT_NAME = "${projectName}"

# Project file map (path -> content)
FILES_DATA = ${filesJson}


def banner() -> None:
    print(r"""
  _______             ______                  
 |__   __|           |  ____|                 
    | | __ _ ___  ___| |__ ___  _ __ __ _  ___ 
    | |/ _\` |/ _ \\/ _ \\  __/ _ \\| '__/ _\` |/ _ \\
    | | (_| |  __/  __/ | | (_) | | | (_| |  __/
    |_|\\__,_|\\___|\\___|_|  \\___/|_|  \\__, |\\___|
                                      __/ |     
                                     |___/      
    """)
    print(f"📦 Extracting & Scaffolding: {PROJECT_NAME}")
    print("=" * 55)


def extract_files(target_dir: Path) -> None:
    target_dir.mkdir(parents=True, exist_ok=True)
    count = 0

    for rel_path, content in FILES_DATA.items():
        file_path = target_dir / rel_path
        file_path.parent.mkdir(parents=True, exist_ok=True)
        
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(content)
        count += 1
        print(f"  ✓ Created: {rel_path}")

    print("=" * 55)
    print(f"✨ Successfully generated {count} files in '{target_dir.resolve()}'!")


def setup_venv_prompt(target_dir: Path) -> None:
    req_file = target_dir / "requirements.txt"
    print("\nNext steps:")
    print(f"  cd {target_dir.name}")
    print("  python -m venv .venv")
    if sys.platform == "win32":
        print("  .venv\\Scripts\\activate")
    else:
        print("  source .venv/bin/activate")
    if req_file.exists():
        print("  pip install -r requirements.txt")
    print("  python main.py\n")


def main() -> None:
    banner()
    current_dir = Path.cwd()
    target = current_dir / PROJECT_NAME
    
    if target.exists() and any(target.iterdir()):
        print(f"⚠️  Warning: Target folder '{target}' already exists and is not empty.")
        resp = input("Proceed and write files? (y/n) [y]: ").strip().lower()
        if resp and resp != "y":
            print("Aborted.")
            sys.exit(0)

    extract_files(target)
    setup_venv_prompt(target)


if __name__ == "__main__":
    main()
`;
}

/**
 * Generate a standalone Bash shell installer script (`install.sh`).
 */
export function generateStandaloneBashInstaller(
  files: Record<string, string>,
  projectName: string = 'TreeForgeProject'
): string {
  let script = `#!/usr/bin/env bash
# TreeForge Standalone Shell Installer for ${projectName}
set -e

echo "🚀 Installing ${projectName}..."
mkdir -p "${projectName}"
cd "${projectName}"

`;

  for (const [path, content] of Object.entries(files)) {
    // Escape backticks and dollar signs for heredoc
    const safeContent = content.replace(/\\/g, '\\\\').replace(/\$/g, '\\$').replace(/`/g, '\\`');
    script += `mkdir -p "$(dirname "${path}")"\n`;
    script += `cat << 'EOF' > "${path}"\n${content}\nEOF\necho "  ✓ ${path}"\n\n`;
  }

  script += `echo "✅ Project created successfully in $(pwd)!"\n`;
  script += `if [ -f "requirements.txt" ]; then\n`;
  script += `  echo "Setting up virtual environment..."\n`;
  script += `  python3 -m venv .venv\n`;
  script += `  source .venv/bin/activate\n`;
  script += `  pip install -r requirements.txt\n`;
  script += `fi\n`;
  script += `echo "🚀 Run 'python3 main.py' to launch."\n`;

  return script;
}
